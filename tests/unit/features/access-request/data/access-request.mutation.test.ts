const BASE = "http://localhost:3000";

describe("useChangeAccessRequestStatusMutation", () => {
  it("calls toast.error when server returns 422", async () => {
    const { toast } = await import("sonner");

    server.use(
      http.put(`${BASE}/access-request/:id`, () =>
        HttpResponse.json({ message: "Validation Error" }, { status: 422 }),
      ),
    );

    const { result } = renderHook(() => useChangeAccessRequestStatusMutation());

    result.current.mutate({
      requestId: 1,
      data: { status: "APPROVED", roles: [] },
    });

    await waitFor(() => expect(toast.error).toHaveBeenCalled());
  });
});
